module mactb;
    logic [15:0] A, B, C;
    logic [15:0] X;

    mac dut (  
        .A(A),
        .B(B),
        .C(C),
        .X(X)
    );

    initial begin
        $display("A B C X");

        // test 1: 1.0 * 2.0 + 3.0 = 5.0
        A = 16'b0011110000000000;
        B = 16'b0100000000000000;
        C = 16'b0100001000000000;
        #10; 
        $display("%b %b %b %b", A, B, C, X);

        // test 2: (-2.0) * 3.0 + 1.0 = -5.0
        A = 16'b1100000000000000;
        B = 16'b0100001000000000;
        C = 16'b0011110000000000;
        #10;
        $display("%b %b %b %b", A, B, C, X);

        // test 3: 0.0 * 2.0 + 1.5 = 1.5
        A = 16'b0000000000000000;
        B = 16'b0100000000000000;
        C = 16'b0011111000000000;
        #10;
        $display("%b %b %b %b", A, B, C, X);

        // test 4: 1.5 * 2.0 + (-1.0) = 2.0
        A = 16'b0011111000000000;
        B = 16'b0100000000000000;
        C = 16'b1011110000000000;
        #10;
        $display("%b %b %b %b", A, B, C, X);

        // test 5: 0.5 * 0.5 + 0.5 = 0.75
        A = 16'b0011100000000000;
        B = 16'b0011100000000000;
        C = 16'b0011100000000000;
        #10;
        $display("%b %b %b %b", A, B, C, X);

        // test 6:(-1.5) * 2.0 + 4.0 = 1.0
        A = 16'b1011111000000000;
        B = 16'b0100000000000000;
        C = 16'b0100010000000000;
        #10;
        $display("%b %b %b %b", A, B, C, X);

        // test 7: 2.0 * 2.0 + (-4.0) = 0.0
        A = 16'b0100000000000000;
        B = 16'b0100000000000000;
        C = 16'b1100010000000000;
        #10;
        $display("%b %b %b %b", A, B, C, X);
        
        // test 8: 1.5 * 1.5 + 0.25 = 2.5
        A = 16'b0011111000000000;
        B = 16'b0011111000000000;
        C = 16'b0011010000000000;
        #10;
        $display("%b %b %b %b", A, B, C, X);

        $finish;
    end

endmodule